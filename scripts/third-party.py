#!/usr/bin/env python3
"""Generate/check the locked Rust dependency inventory and original license texts."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'licenses/rust-dependencies.txt'
TARGETS = ['aarch64-apple-darwin', 'x86_64-pc-windows-msvc']


def generated_files():
    rows = set()
    identities = set()
    for target in TARGETS:
        lines = subprocess.check_output(
            ['cargo', 'tree', '--locked', '-e', 'normal', '--target', target,
             '--prefix', 'none', '-f', '{p}\t{l}'],
            cwd=ROOT, text=True, timeout=300).splitlines()
        for line in lines:
            if not line.strip():
                continue
            package, _, license_text = line.replace(' (*)', '').partition('\t')
            name, version = package.split(' ')[:2]
            if name.startswith('tezbar-color-shades'):
                continue
            rows.add(f'{name} {version}\t{license_text.strip()}')
            identities.add((name, version.removeprefix('v')))

    # Includes procedural macro dependencies reported by cargo tree as well as
    # target runtime crates. Preserve their own copyrights and compound licenses.
    metadata = json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--locked', '--format-version=1'],
        cwd=ROOT, text=True, timeout=300))
    result = {}
    for package in metadata['packages']:
        identity = (package['name'], package['version'])
        if identity not in identities:
            continue
        source = Path(package['manifest_path']).parent
        sources = {p for p in source.iterdir() if p.is_file()
                   and p.name.lower().startswith(('license', 'notice', 'copying', 'copyright'))}
        if package.get('license_file'):
            sources.add(source / package['license_file'])
        if not sources:
            raise SystemExit('No original license text found for ' + str(identity))
        destination = ROOT / 'licenses/rust' / '-'.join(identity)
        for path in sorted(sources):
            result[destination / path.name] = path.read_bytes()
    header = ('# Locked Rust dependencies for macOS arm64 and/or Windows x64, '
              'including procedural macros (generated by scripts/third-party.py).\n')
    result[OUT] = (header + '\n'.join(sorted(rows)) + '\n').encode()
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generated_files()
    if args.check:
        for path, data in expected.items():
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(str(path.relative_to(ROOT)) + ' is stale; run scripts/third-party.py')
        actual = {p for p in (ROOT / 'licenses/rust').rglob('*') if p.is_file()}
        assert actual == set(expected) - {OUT}, 'Unexpected Rust license files'
        print('Locked dependency inventory and original license texts verified')
    else:
        for path, data in expected.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f'Wrote dependency inventory and {len(expected) - 1} license/notice files')
