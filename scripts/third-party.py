#!/usr/bin/env python3
"""Generate/check the locked Rust dependency inventory and original license texts."""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'licenses/rust-dependencies.txt'
INDEX = ROOT / 'licenses/THIRD_PARTY.md'
TARGETS = ['aarch64-apple-darwin', 'x86_64-pc-windows-msvc']


def generated_files():
    # cargo tree -e normal misses build-dependency closure. Walk the filtered
    # locked metadata graph for both targets, including normal + build edges.
    packages = {}
    rows = set()
    for target in TARGETS:
        metadata = json.loads(subprocess.check_output(
            ['cargo', 'metadata', '--locked', '--format-version=1', '--filter-platform', target],
            cwd=ROOT, text=True, timeout=300))
        nodes = {node['id']: node for node in metadata['resolve']['nodes']}
        queue = [metadata['resolve']['root']]
        selected = set()
        while queue:
            identity = queue.pop()
            if identity in selected:
                continue
            selected.add(identity)
            queue.extend(dep['pkg'] for dep in nodes[identity]['deps']
                         if any(kind['kind'] in (None, 'build') for kind in dep['dep_kinds']))
        for package in metadata['packages']:
            if package['id'] in selected and package['source'] is not None:
                packages[package['id']] = package
                rows.add(f"{package['name']} v{package['version']}\t{package['license']}")
    result = {}
    for package in packages.values():
        identity = (package['name'], package['version'])
        source = Path(package['manifest_path']).parent
        sources = {p for p in source.iterdir() if p.is_file()
                   and p.name.lower().startswith(('license', 'notice', 'copying', 'copyright'))}
        if package.get('license_file'):
            sources.add(source / package['license_file'])
        if not sources:
            raise SystemExit('No original license text found for ' + str(identity))
        destination = ROOT / 'licenses/rust' / '-'.join(identity)
        for path in sorted(sources):
            result[destination / path.name] = path.read_bytes()
    header = ('# Locked Rust dependencies for macOS arm64 and/or Windows x64, '
              'including normal/build closure and procedural macros (generated by scripts/third-party.py).\n')
    result[OUT] = (header + '\n'.join(sorted(rows)) + '\n').encode()
    lines = ['# Locked Rust dependency notices', '',
             'Normal and build dependencies for macOS arm64 and Windows x64.', '',
             '| Crate | Version | Licenses | Bundled documents |', '|---|---|---|---|']
    for package in sorted(packages.values(), key=lambda p: (p['name'], p['version'])):
        folder = ROOT / 'licenses/rust' / (package['name'] + '-' + package['version'])
        documents = ', '.join('[' + file.name + '](' + file.relative_to(INDEX.parent).as_posix() + ')'
                              for file in sorted(result) if file.parent == folder)
        lines.append(f"| {package['name']} | {package['version']} | {package['license']} | {documents} |")
    result[INDEX] = ('\n'.join(lines) + '\n').encode()
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generated_files()
    if args.check:
        for path, data in expected.items():
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(str(path.relative_to(ROOT)) + ' is stale; run scripts/third-party.py')
        actual = {p for p in (ROOT / 'licenses/rust').rglob('*') if p.is_file()}
        assert actual == set(expected) - {OUT, INDEX}, 'Unexpected Rust license files'
        print('Locked dependency inventory and original license texts verified')
    else:
        for path, data in expected.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f'Wrote dependency inventory and {len(expected) - 2} license/notice files')
